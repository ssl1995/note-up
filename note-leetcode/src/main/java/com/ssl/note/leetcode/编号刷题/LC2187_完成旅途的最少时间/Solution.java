package com.ssl.note.leetcode.编号刷题.LC2187_完成旅途的最少时间;

public class Solution {

  /**
   * LC2187_完成旅途的最少时间
   * 给你一个数组 time ，其中 time[i] 表示第 i 辆公交车完成 一趟旅途 所需要花费的时间。
   * 每辆公交车可以 连续 完成多趟旅途，也就是说，一辆公交车当前旅途完成后，
   * 可以 立马开始 下一趟旅途。每辆公交车 独立 运行，也就是说可以同时有多辆公交车在运行且互不影响。
   * 给你一个整数 totalTrips ，表示所有公交车 总共 需要完成的旅途数目。
   * 请你返回完成 至少 totalTrips 趟旅途需要花费的 最少 时间。
   * 输入：time = [1,2,3], totalTrips = 5
   * 输出：3
   * 解释：
   * - 时刻 t = 1 ，每辆公交车完成的旅途数分别为 [1,0,0] 。
   * 已完成的总旅途数为 1 + 0 + 0 = 1 。
   * - 时刻 t = 2 ，每辆公交车完成的旅途数分别为 [2,1,0] 。
   * 已完成的总旅途数为 2 + 1 + 0 = 3 。
   * - 时刻 t = 3 ，每辆公交车完成的旅途数分别为 [3,1,1] 。
   * 已完成的总旅途数为 3 + 1 + 1 = 5 。
   * 所以总共完成至少 5 趟旅途的最少时间为 3 。
   * 思路：二分答案
   * 1. 单调性：时间越长，能完成的旅途越多，答案可二分。
   * 2. 上界：只用最快的一辆车跑完 w 趟，即 min * w。
   * 时间复杂度：O(n * log(min * w))
   */
  public static long minimumTime(int[] arr, int w) {
    // 找出最快一辆车的单趟时间，作为二分上界的依据
    int min = Integer.MAX_VALUE;
    for (int x : arr) {
      min = Math.min(min, x);
    }
    long ans = 0;
    // 在 [0, min * w] 上二分最小可行时间
    for (long l = 0, r = (long) min * w, m; l <= r; ) {
      m = l + ((r - l) >> 1);
      // 这里逻辑和课上讲的不同
      // 课上讲的题意，是需要等多少人才能获得服务，你是第w+1个
      // 在线测试的题意，是需要完成w趟旅行
      // m 分钟内能完成的旅途数 >= w，说明 m 可行，记录答案并尝试更小的时间
      if (f(arr, m) >= w) {
        ans = m;
        r = m - 1;
      } else {
        // 完不成 w 趟，说明时间不够，增大时间
        l = m + 1;
      }
    }
    return ans;
  }

  // 计算所有公交车在 time 时间内总共能完成多少趟旅途
  public static long f(int[] arr, long time) {
    long ans = 0;
    for (int num : arr) {
      // 这里逻辑和课上讲的不同
      // 课上讲的题意，计算time时间内，(完成 + 开始)服务的人数，需要+1
      // 在线测试的题意，计算time时间内，能完成多少旅行，不需要+1
      // 每辆车独立完成 time / num 趟，直接累加
      ans += (time / num);
    }
    return ans;
  }
}
