package com.ssl.note.leetcode.编号刷题.LCP74_最强祝福力场;

import java.util.Arrays;

public class Solution {

  /**
   * LCP74_最强祝福力场
   * 小扣在探索丛林的过程中，无意间发现了传说中“落寞的黄金之都”。而在这片建筑废墟的地带中，小扣使用探测仪监测到了存在某种带有「祝福」效果的力场。 经过不断的勘测记录，小扣将所有力场的分布都记录了下来。forceField[i] = [x,y,side] 表示第 i 片力场将覆盖以坐标 (x,y) 为中心，边长为 side 的正方形区域。*
   * 若任意一点的 力场强度 等于覆盖该点的力场数量，请求出在这片地带中 力场强度 最强处的 力场强度。
   * 示例：
   * 输入： forceField = [[4,4,6],[7,5,3],[1,6,2],[5,6,3]]
   * 输出：3
   *
   * 题目本质：求平面上被最多矩形覆盖的点的覆盖次数（二维区域最大重叠次数）
   * 四板斧组合：
   * 1、坐标翻倍(×2)：side为奇数时，边界 x±side/2 是 .5 小数；×2 后全变整数，且等比缩放不改变重叠关系
   * 2、离散化：坐标范围太大(10^9级)无法直接开数组，但n个矩形最多2n个边界，
   *    只有边界的相对顺序影响答案，把大坐标压缩成 1~2n 的连续编号
   * 3、二维差分：每个矩形区域 +1，O(1)/次
   * 4、前缀和还原：还原差分数组的同时扫出最大值
   * 复杂度：排序O(nlogn) + 映射O(nlogn) + 还原O(n²) = 总O(n²)
   */
  public int fieldOfGreatestBlessing(int[][] fields) {
    // 1、第一遍遍历：坐标翻倍，收集所有矩形的边界坐标
    int n = fields.length;
    // n个矩形，最多有2n个坐标
    // xs:收集x轴上的坐标
    long[] xs = new long[n << 1];
    // ys:收集y轴上的坐标
    long[] ys = new long[n << 1];
    // 技巧1-坐标翻倍：覆盖区间是闭区间 [x-side/2, x+side/2]，side为奇数时边界是 .5 小数
    // 示例：力场② (7,5,3)，原始x区间 [5.5, 8.5]，×2后 [11, 17]，小数消失
    // 注意用 long：坐标×2再±side可能超 int
    for (int i = 0, k = 0, p = 0; i < n; i++) {
      long x = fields[i][0];
      long r = fields[i][2];
      long y = fields[i][1];
      xs[k++] = (x << 1) - r; // 左边界×2
      xs[k++] = (x << 1) + r; // 右边界×2
      ys[p++] = (y << 1) - r; // 上边界×2
      ys[p++] = (y << 1) + r; // 下边界×2
    }
    // 示例：输入 [[4,4,6],[7,5,3],[1,6,2],[5,6,3]]
    // ①(4,4,6): x[2,14]  y[2,14]
    // ②(7,5,3): x[11,17] y[7,13]
    // ③(1,6,2): x[0,4]   y[10,14]
    // ④(5,6,3): x[7,13]  y[9,15]
    // xs收集：[2,14, 11,17, 0,4, 7,13]，ys收集：[2,14, 7,13, 10,14, 9,15]

    // 2、第二遍遍历：离散化 第2步，二分映射成编号，二维差分区域+1
    // 技巧2-离散化 第1步：排序+去重，返回有效长度
    // xs数组中，排序了且相同值只留一份，返回有效长度
    // 示例：xs [2,14,11,17,0,4,7,13] → 排序去重 [0,2,4,7,11,13,14,17]，sizex=8
    int sizex = sort(xs);
    // ys数组中，排序了且相同值只留一份，返回有效长度
    // 示例：ys [2,14,7,13,10,14,9,15] → 排序去重 [2,7,9,10,13,14,15]，sizey=7
    int sizey = sort(ys);
    // 离散化收益：差分数组只需开 10(8+2)×9(7+2)，而不是按坐标开 18×16 甚至更大
    int[][] diff = new int[sizex + 2][sizey + 2];

    for (int i = 0, a, b, c, d; i < n; i++) {
      long x = fields[i][0];
      long y = fields[i][1];
      long r = fields[i][2];
      // 确定左上和右下的相对编号(原始坐标->离散化的坐标)：(a,b)和(c,d)
      a = rank(xs, (x << 1) - r, sizex); // 左边界编号
      b = rank(ys, (y << 1) - r, sizey); // 上边界编号
      c = rank(xs, (x << 1) + r, sizex); // 右边界编号
      d = rank(ys, (y << 1) + r, sizey); // 下边界编号
      // 技巧3-二维差分：给 [a,c]×[b,d] 整个区域 +1，表示这片区域被一个力场覆盖
      // 示例：①[2,14]×[2,14] → 编号 x[2,7] y[1,6]；④[7,13]×[9,15] → 编号 x[4,6] y[3,7]
      add(diff, a, b, c, d);
    }
    int ans = 0;
    // 3、求最大立场，就是求diff还原后存在的最大值
    // 技巧4-前缀和还原：diff[i][j] 变为该格子被力场覆盖的次数，同时扫出最大值
    // 示例：还原后 编号x∈[5,6]、y∈[3,5] 的格子被①②④三个力场同时覆盖 → 值为3
    // 对应回原坐标：x∈[5.5,6.5]、y∈[4.5,6.5] 被3个力场覆盖，ans=3
    // O(n^2)
    for (int i = 1; i < diff.length; i++) {
      for (int j = 1; j < diff[0].length; j++) {
        diff[i][j] += diff[i - 1][j] + diff[i][j - 1] - diff[i - 1][j - 1];
        ans = Math.max(ans, diff[i][j]);
      }
    }
    return ans;
  }

  // 离散化第1步：排序 + 双指针去重，返回有效长度
  // 易错：去重比较的是"上一个有效值" nums[size-1]，不是 nums[i-1]
  // [50,70,30,70,30,60] 长度6
  // [30,30,50,60,70,70]
  // [30,50,60,70] 60 -> 3
  //  1  2  3  4
  // 长度4，
  public int sort(long[] nums) {
    Arrays.sort(nums);
    int size = 1;
    for (int i = 1; i < nums.length; i++) {
      if (nums[i] != nums[size - 1]) {
        nums[size++] = nums[i]; // 与上一个有效值不同才收录
      }
    }
    return size;
  }

  // nums 有序数组，有效长度是size，0~size-1范围上无重复值
  // 已知v一定在nums[0~size-1]，返回v所对应的编号
  // 技巧：找 >=v 的最左位置，因为v一定存在，正好定位到它自己
  // 易错：返回 ans+1 是 1-based 编号，给差分数组第0行/列留哨兵位；写漏会导致add访问-1越界
  // 示例：[30,50,60,70](size=4) 中查60 → 下标2 → 编号3
  public int rank(long[] nums, long v, int size) {
    int l = 0;
    int r = size - 1;
    int m, ans = 0;
    while (l <= r) {
      m = (l + r) / 2;
      if (nums[m] >= v) {
        ans = m;
        r = m - 1;
      } else {
        l = m + 1;
      }
    }
    return ans + 1;
  }

  // 二维差分
  // 给 (a,b)~(c,d) 整个区域 +1，只动4个角
  // 记忆口诀：左上加、右下加，另外两个减（与前缀和查询"减两块加回角"规律呼应）
  public void add(int[][] diff, int a, int b, int c, int d) {
    diff[a][b] += 1;         // 左上角：+
    diff[c + 1][d + 1] += 1; // 右下角斜对角：+（补回多减的）
    diff[c + 1][b] -= 1;     // 下边界的下一行：-
    diff[a][d + 1] -= 1;     // 右边界的下一列：-
  }
}
