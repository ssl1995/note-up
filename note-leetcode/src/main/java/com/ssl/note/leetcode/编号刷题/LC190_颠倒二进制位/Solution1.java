package com.ssl.note.leetcode.编号刷题.LC190_颠倒二进制位;

public class Solution1 {

  /**
   * LC190_逆序二进制位
   * 颠倒给定的 32 位有符号整数的二进制位。
   * n：43261596	二进制：00000010100101000001111010011100
   * 答：964176192	二进制：00111001011110000010100101000000
   */
  public int reverseBits(int n) {
    // 第1步：相邻的 1 位互相交换
    // 0xaaaaaaaa = 1010...1010(所有奇数位为1), 0x55555555 = 0101...0101(所有偶数位为1)
    // 取出奇数位的1右移到偶数位 | 取出偶数位的1左移到奇数位
    n = ((n & 0xaaaaaaaa) >>> 1) | ((n & 0x55555555) << 1);

    // 第2步：相邻的 2 位块互相交换
    // 0xcccccccc = 1100...1100, 0x33333333 = 0011...0011
    n = ((n & 0xcccccccc) >>> 2) | ((n & 0x33333333) << 2);

    // 第3步：相邻的 4 位块(半个字节)互相交换
    // 0xf0f0f0f0 = 11110000..., 0x0f0f0f0f = 00001111...
    n = ((n & 0xf0f0f0f0) >>> 4) | ((n & 0x0f0f0f0f) << 4);

    // 第4步：相邻的 8 位块(整个字节)互相交换
    n = ((n & 0xff00ff00) >>> 8) | ((n & 0x00ff00ff) << 8);

    // 第5步：高 16 位和低 16 位整体交换，32位全部逆序完成
    // 注意：右移必须用 >>> (无符号右移)，否则负数会补1导致结果错误
    n = (n >>> 16) | (n << 16);
    return n;
  }

  public static void main(String[] args) {
    Solution1 solution = new Solution1();
    int n = 43261596;
    System.out.println(solution.reverseBits(n));
  }
}
