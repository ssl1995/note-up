package com.ssl.note.leetcode.编号刷题.LC461_汉明距离;

/**
 * @author SongShengLin
 * @date 2022/2/26 11:22 PM
 * @description
 */
public class Solution2 {

  /**
   * 汉明距离
   * 输入：x = 1, y = 4
   * 输出：2
   * 解释：有两个位置不同
   * 1   (0 0 0 1)
   * 4   (0 1 0 0)
   */
  public int hammingDistance(int x, int y) {
    // 二进制不同位置 = 将所有位置的1放在同一个数上 = 异或
    int num = x ^ y;

    return cntOnes(num);
  }

  // 返回n的二进制中有几个1 (即统计1的个数, popcount)
  // 分治累加法(SWAR)：和LC190逆序位是同一套思想
  // 按 1位 → 2位 → 4位 → 8位 → 16位 的粒度，把相邻两块的"1的个数"加起来
  // 每轮结束后，每个小格里存的就是这个小格内1的个数，5轮后低32位就是总数
  //
  // 以 8 位 0110 1011 示意全程：
  //   初始每1位就是它自己的计数:  0 1 1 0 1 0 1 1
  //   第1步(相邻1位相加,存进2位格):  01 01 01 10   (每2位=该2位中1的个数)
  //   第2步(相邻2位相加,存进4位格):  0010 0011     (每4位=该4位中1的个数)
  //   第3步(相邻4位相加,存进8位格):  00000101 = 5  ✓ 共5个1
  public static int cntOnes(int n) {
    // 第1步：相邻的 1 位计数相加，结果存进每 2 位的小格
    // 0x55555555 = 0101...0101，分别取出偶数位的值和奇数位的值，相加
    // 2位格最大存 2(二进制10)，不会溢出
    n = (n & 0x55555555) + ((n >>> 1) & 0x55555555);

    // 第2步：相邻的 2 位格相加，结果存进每 4 位的小格
    // 0x33333333 = 0011...0011，4位格最大存 4(0100)，不会溢出
    n = (n & 0x33333333) + ((n >>> 2) & 0x33333333);

    // 第3步：相邻的 4 位格相加，结果存进每 8 位的小格(8位最大存8)
    n = (n & 0x0f0f0f0f) + ((n >>> 4) & 0x0f0f0f0f);

    // 第4步：相邻的 8 位格相加，结果存进每 16 位的小格(16位最大存16)
    n = (n & 0x00ff00ff) + ((n >>> 8) & 0x00ff00ff);

    // 第5步：高16位和低16位的计数相加，32位中1的总数(最大32)就是最终结果
    // 最后一步掩码 0x0000ffff 其实可省略(数值已≤32)，写上是为了形式统一
    n = (n & 0x0000ffff) + ((n >>> 16) & 0x0000ffff);
    return n;
  }

  public static void main(String[] args) {
    Solution2 solution = new Solution2();
    int x = 1;
    int y = 4;
    System.out.println(solution.hammingDistance(x, y));
  }
}
